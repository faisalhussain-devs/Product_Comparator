import json
from collections import Counter
from pathlib import Path

# ===============================
# Paths
# ===============================
DATA_PATH = Path(r"E:\Product Comparator\final_aspa_data_clustered_with_sentiments.json")
OUTPUT_PATH = Path(r"E:\Product Comparator\final_aspa_data_merged_with_sentiments.json")

# ===============================
# Label Merge Mapping (Dict)
# ===============================

# Create reverse mapping: child → parent
reverse_label_map = {}
for parent, children in label_merge_map.items():
    for child in children:
        reverse_label_map[child] = parent

# ===============================
# Load Dataset
# ===============================
print("Loading data...")
with open(DATA_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)

print(f"Loaded {len(data)} reviews.\n")

# ===============================
# Merge Labels and Sentiments
# ===============================
def resolve_sentiment(existing, new):
    """
    Resolve sentiment conflict when multiple child aspects merge into one parent.
    Priority: positive > neutral > negative
    """
    priority = {"positive": 3, "positive": 2, "neutral": 1}
    return new if priority.get(new, 0) >= priority.get(existing, 0) else existing

merged_data = []
for item in data:
    merged_labels = {}
    for label, sentiment in item["label"].items():
        # Map child → parent if applicable
        merged_label = reverse_label_map.get(label, label)

        # Handle duplicates by sentiment priority
        if merged_label in merged_labels:
            merged_labels[merged_label] = resolve_sentiment(merged_labels[merged_label], sentiment)
        else:
            merged_labels[merged_label] = sentiment

    merged_data.append({
        "input": item["input"],
        "label": merged_labels
    })

# ===============================
# Count New Label Frequencies
# ===============================
merged_labels_flat = [label for item in merged_data for label in item["label"]]
label_counts = Counter(merged_labels_flat)

# ===============================
# Summary
# ===============================
print(f"🔹 Total reviews processed: {len(merged_data)}")
print(f"🔹 Unique labels after merging: {len(label_counts)}\n")

for label, count in label_counts.most_common(10):
    print(f"{label:80s} → {count}")

# ===============================
# Save Merged Output
# ===============================
with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
    json.dump(merged_data, f, indent=2, ensure_ascii=False)

print(f"\n✅ Merged dataset with sentiments saved to: {OUTPUT_PATH}")
